"""Fast source, provenance and autoload checks. No DB, SMTP or production access."""
import argparse
import ast
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--php', required=True)
    parser.add_argument('--node', required=True)
    args = parser.parse_args()
    checks = []

    def check(name, passed):
        if not passed:
            raise ValueError(name)
        checks.append({'name': name, 'passed': True})

    for folder in ['app', 'public', 'tests', 'tools']:
        for file in (ROOT / folder).rglob('*.php'):
            if 'runtime' in file.relative_to(ROOT).parts or file.name.endswith('.local.php'):
                continue
            result = subprocess.run([args.php, '-l', str(file)], capture_output=True)
            check('PHP syntax: ' + file.relative_to(ROOT).as_posix(), result.returncode == 0)
    for folder in ['tools', 'tests']:
        for file in (ROOT / folder).rglob('*.py'):
            if 'runtime' not in file.relative_to(ROOT).parts:
                ast.parse(file.read_text(encoding='utf-8'), filename=str(file))
    check('Python sources parse without generated bytecode', True)
    for file in list((ROOT / 'public/assets').glob('*.js')) + list((ROOT / 'public/assets/home').glob('*.js')) + list((ROOT / 'tests').glob('*.mjs')) + list((ROOT / 'tests').glob('*.cjs')):
        result = subprocess.run([args.node, '--check', str(file)], capture_output=True)
        check('JavaScript syntax: ' + file.relative_to(ROOT).as_posix(), result.returncode == 0)
    for file in (ROOT / 'app').rglob('*.php'):
        if 'Vendor' in file.relative_to(ROOT).parts:
            continue
        source = file.read_text(encoding='utf-8')
        namespace = re.search(r'^namespace\s+(App[\\\w]*);', source, re.M)
        declaration = re.search(r'^(?:(?:final|abstract|readonly)\s+)*class\s+(\w+)', source, re.M)
        if namespace and declaration:
            expected = 'app/' + namespace[1][4:].replace('\\', '/') + '/' + declaration[1] + '.php'
            check('Case-sensitive PSR-4 path: ' + declaration[1], expected == file.relative_to(ROOT).as_posix())
    for file in list((ROOT / 'contracts').rglob('*.json')) + [ROOT / 'composer.json', ROOT / 'package.json', ROOT / 'release.json']:
        json.loads(file.read_text(encoding='utf-8'))
    check('JSON contracts and project manifests parse', True)
    dependencies = json.loads((ROOT / 'docs/DEPENDENCIES.json').read_text(encoding='utf-8'))
    for asset in dependencies['production_assets']:
        name = asset['file']
        file = ROOT / 'public/assets' / (name if '/' in name else 'vendor/' + name)
        check('Pinned production asset: ' + name, file.is_file() and hashlib.sha256(file.read_bytes()).hexdigest() == asset['sha256'])
    for dependency in dependencies['php_package_dependencies']:
        for name, expected in dependency['files_sha256'].items():
            file = ROOT / dependency.get('path', 'app/Vendor/PHPMailer') / name
            check('Pinned PHP dependency: ' + name, hashlib.sha256(file.read_bytes()).hexdigest() == expected)
    archive = ROOT / 'OpenBread_Codex_v1_2026-10-23'
    historical_manifest = archive / 'HASHES.sha256'
    if archive.exists() and not historical_manifest.is_file():
        raise ValueError('Historical package is present but its integrity manifest is missing.')
    for line in historical_manifest.read_text(encoding='utf-8').splitlines() if historical_manifest.is_file() else []:
        if not line.strip():
            continue
        expected, relative = line.split('  ', 1)
        file = archive / relative
        check('Historical bytes: ' + relative, file.resolve().is_relative_to(archive.resolve()) and hashlib.sha256(file.read_bytes()).hexdigest() == expected)
    report = {'passed': len(checks), 'failed': 0, 'checks': checks,
              'historical_package': 'verified_original_bytes' if historical_manifest.is_file() else 'not_distributed_with_source'}
    output = ROOT / 'tests/runtime/reports'
    output.mkdir(parents=True, exist_ok=True)
    (output / 'repository-checks.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    print(json.dumps({'passed': len(checks), 'failed': 0}))


if __name__ == '__main__':
    main()
