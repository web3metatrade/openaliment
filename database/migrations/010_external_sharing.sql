CREATE TABLE IF NOT EXISTS external_connections (
 id CHAR(32) PRIMARY KEY,
 tenant_id CHAR(32) NOT NULL,
 provider_id VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 remote_organization_ref VARCHAR(180) NOT NULL,
 transport VARCHAR(30) NOT NULL DEFAULT 'producer_package',
 credential_ref VARCHAR(100) NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'pending',
 verified_at DATETIME NULL,
 verified_by CHAR(32) NULL,
 last_error_code VARCHAR(60) NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY external_connection_tenant (tenant_id,id),
 UNIQUE KEY external_connection_provider (tenant_id,provider_id),
 FOREIGN KEY (tenant_id) REFERENCES organizations(id),
 FOREIGN KEY (provider_id) REFERENCES external_providers(id),
 FOREIGN KEY (verified_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS external_sharing_grants (
 id CHAR(32) PRIMARY KEY,
 tenant_id CHAR(32) NOT NULL,
 connection_id CHAR(32) NOT NULL,
 trade_item_id CHAR(32) NOT NULL,
 grant_key CHAR(32) NOT NULL,
 version INT UNSIGNED NOT NULL,
 previous_id CHAR(32) NULL,
 action VARCHAR(24) NOT NULL,
 fields_json TEXT NOT NULL,
 asset_ids_json TEXT NOT NULL,
 licenses_json TEXT NOT NULL,
 mode VARCHAR(24) NOT NULL DEFAULT 'manual',
 actor_id CHAR(32) NOT NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY external_grant_tenant (tenant_id,id),
 UNIQUE KEY external_grant_version (tenant_id,grant_key,version),
 KEY external_grant_item (tenant_id,trade_item_id,version),
 FOREIGN KEY (tenant_id,connection_id) REFERENCES external_connections(tenant_id,id),
 FOREIGN KEY (tenant_id,trade_item_id) REFERENCES trade_items(tenant_id,id),
 FOREIGN KEY (tenant_id,previous_id) REFERENCES external_sharing_grants(tenant_id,id),
 FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS external_publications (
 id CHAR(32) PRIMARY KEY,
 tenant_id CHAR(32) NOT NULL,
 connection_id CHAR(32) NOT NULL,
 trade_item_id CHAR(32) NOT NULL,
 label_id CHAR(32) NOT NULL,
 grant_id CHAR(32) NOT NULL,
 payload_sha256 CHAR(64) NOT NULL,
 payload_json MEDIUMTEXT NOT NULL,
 base_remote_revision VARCHAR(60) NULL,
 base_remote_json MEDIUMTEXT NULL,
 state VARCHAR(24) NOT NULL DEFAULT 'pending',
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL,
 lease_until DATETIME NULL,
 lease_token CHAR(32) NULL,
 remote_result_json MEDIUMTEXT NULL,
 confirmed_at DATETIME NULL,
 created_at DATETIME NOT NULL,
 UNIQUE KEY external_publication_identity (tenant_id,connection_id,label_id,payload_sha256),
 KEY external_publication_due (state,available_at),
 FOREIGN KEY (tenant_id,connection_id) REFERENCES external_connections(tenant_id,id),
 FOREIGN KEY (tenant_id,trade_item_id) REFERENCES trade_items(tenant_id,id),
 FOREIGN KEY (tenant_id,label_id) REFERENCES product_info_versions(tenant_id,id),
 FOREIGN KEY (tenant_id,grant_id) REFERENCES external_sharing_grants(tenant_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
